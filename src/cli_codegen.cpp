CliCatalog build_cli_catalog(const CommandFactory& command_factory) {
    CliCatalog catalog;
    catalog.program = "osmium";
    catalog.version = get_osmium_version();

    for (const auto& [cmd_name, cmd_desc] : command_factory.help()) {
        auto cmd = command_factory.create_command(cmd_name);
        if (cmd) {
            catalog.commands.push_back(cmd->describe_options());
        }
    }

    return catalog;
}

std::string generate_zsh_completion(const CliCatalog& catalog) {
    std::ostringstream out;
    out << "#compdef osmium\n"
        << "# Generated by osmium --generate-completions zsh (version " << catalog.version << ")\n\n"
        << "_osmium() {\n"
        << "    local -a osmium_commands\n"
        << "    osmium_commands=(\n";
    for (const auto& cmd : catalog.commands) {
        out << "        '" << escape_zsh_single_quoted(cmd.name) << ':'
            << escape_zsh_desc(cmd.description) << "'\n";
    }
    out << "    )\n"
        << "    if (( CURRENT > 2 )); then\n"
        << "        local cmd=${words[2]}\n"
        << "        curcontext=\"${curcontext%:*:*}:osmium-$cmd\"\n"
        << "        (( CURRENT-- ))\n"
        << "        shift words\n"
        << "        (( $+functions[_osmium-$cmd] )) && _osmium-$cmd\n"
        << "    else\n"
        << "        _describe -t osmium-commands 'osmium subcommand' osmium_commands\n"
        << "    fi\n"
        << "}\n\n";

    for (const auto& cmd : catalog.commands) {
        out << "_osmium-" << cmd.name << "() {\n";
        if (cmd.options.empty() && cmd.positionals.empty()) {
            if (cmd.name == "help") {
                out << "    local -a osmium_help_topics\n"
                    << "    osmium_help_topics=(";
                for (const auto& c : catalog.commands) {
                    out << c.name << ' ';
                }
                out << "file-formats index-types output-headers)\n"
                    << "    _describe -t osmium-help-topics 'osmium help topics' osmium_help_topics\n";
            } else {
                out << "    return 0\n";
            }
            out << "}\n\n";
            continue;
        }

        std::vector<std::string> specs;
        for (const auto& opt : cmd.options) {
            const std::string desc = escape_zsh_desc(opt.description);
            const std::string arg_suffix = opt.takes_value
                ? (":" + escape_zsh_desc(opt.long_name) + ":")
                : "";
            if (!opt.short_name.empty()) {
                if (opt.is_repeatable) {
                    specs.push_back("'*-" + opt.short_name + "[" + desc + "]" + arg_suffix + "'");
                    specs.push_back("'*--" + opt.long_name + (opt.takes_value ? "=" : "") + "[" + desc + "]" + arg_suffix + "'");
                } else {
                    specs.push_back("'(--" + opt.long_name + ")-" + opt.short_name + "[" + desc + "]" + arg_suffix + "'");
                    specs.push_back("'(-" + opt.short_name + ")--" + opt.long_name + (opt.takes_value ? "=" : "") + "[" + desc + "]" + arg_suffix + "'");
                }
            } else {
                const std::string prefix = opt.is_repeatable ? "*" : "";
                specs.push_back("'" + prefix + "--" + opt.long_name + (opt.takes_value ? "=" : "") + "[" + desc + "]" + arg_suffix + "'");
            }
        }

        for (std::size_t i = 0; i < cmd.positionals.size(); ++i) {
            const auto& pos = cmd.positionals[i];
            const std::string pos_desc = escape_zsh_desc(pos.name);
            if (pos.is_variadic) {
                specs.push_back("'*:" + pos_desc + ":_files'");
            } else {
                specs.push_back("'" + std::to_string(i + 1) + ":" + pos_desc + ":_files'");
            }
        }

        out << "    _arguments -S :";
        for (const auto& spec : specs) {
            out << " \\\n        " << spec;
        }
        out << "\n}\n\n";
    }

    out << "_osmium \"$@\"\n";
    return out.str();
}

std::string generate_bash_completion(const CliCatalog& catalog) {
    std::ostringstream out;
    out << "# Bash completion for Osmium tool.\n"
        << "# Generated by osmium --generate-completions bash (version " << catalog.version << ")\n\n"
        << "_osmium_commands=\"";
    for (std::size_t i = 0; i < catalog.commands.size(); ++i) {
        if (i > 0) {
            out << ' ';
        }
        out << catalog.commands[i].name;
    }
    out << "\"\n\n";

    out << "__osmium_opts()\n"
        << "{\n"
        << "    case $1 in\n";
    for (const auto& cmd : catalog.commands) {
        out << "        " << cmd.name << ")\n"
            << "            echo \"";
        bool first = true;
        for (const auto& opt : cmd.options) {
            if (!opt.short_name.empty()) {
                if (!first) out << ' ';
                out << '-' << opt.short_name;
                first = false;
            }
            if (!first) out << ' ';
            out << "--" << opt.long_name;
            first = false;
        }
        out << "\";;\n";
    }
    out << "    esac\n"
        << "}\n\n";

    out << "_osmium()\n"
        << "{\n"
        << "    local cur prev words cword\n"
        << "    cur=\"${COMP_WORDS[COMP_CWORD]}\"\n"
        << "    prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n"
        << "    if [[ $COMP_CWORD -eq 1 ]]; then\n"
        << "        COMPREPLY=( $(compgen -W \"$_osmium_commands --help --version\" -- \"$cur\") )\n"
        << "        return 0\n"
        << "    fi\n"
        << "    local cmd=\"${COMP_WORDS[1]}\"\n"
        << "    if [[ $cmd == help ]]; then\n"
        << "        COMPREPLY=( $(compgen -W \"$_osmium_commands file-formats index-types output-headers\" -- \"$cur\") )\n"
        << "        return 0\n"
        << "    fi\n"
        << "    if [[ $cur == -* ]]; then\n"
        << "        COMPREPLY=( $(compgen -W \"$(__osmium_opts \"$cmd\")\" -- \"$cur\") )\n"
        << "        return 0\n"
        << "    fi\n"
        << "    COMPREPLY=( $(compgen -f -- \"$cur\") )\n"
        << "}\n\n"
        << "complete -F _osmium osmium\n";

    return out.str();
}

std::string generate_man_options(const CliCatalog& catalog, const std::string& command_filter) {
    std::ostringstream out;
    if (!command_filter.empty()) {
        for (const auto& cmd : catalog.commands) {
            if (cmd.name == command_filter) {
                emit_man_command_options(out, cmd, false);
                return out.str();
            }
        }
        throw argument_error{"Unknown command '" + command_filter + "' for man-options generation."};
    }

    for (const auto& cmd : catalog.commands) {
        if (cmd.options.empty()) {
            continue;
        }
        emit_man_command_options(out, cmd, true);
    }
    return out.str();
}

std::string generate_json_catalog(const CliCatalog& catalog) {
    return rfl::json::write(catalog, rfl::json::pretty) + "\n";
}

std::string generate_completions(const CommandFactory& command_factory,
                                 const std::string& format,
                                 const std::string& command_filter) {
    const auto catalog = build_cli_catalog(command_factory);
    if (format == "zsh") {
        return generate_zsh_completion(catalog);
    }
    if (format == "bash") {
        return generate_bash_completion(catalog);
    }
    if (format == "man-options") {
        return generate_man_options(catalog, command_filter);
    }
    if (format == "json") {
        return generate_json_catalog(catalog);
    }
    throw argument_error{"Unknown completion format '" + format + "'. Expected one of: zsh, bash, man-options, json."};
}

