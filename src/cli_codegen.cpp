std::string escape_zsh_single_quoted(const std::string& text) {
    std::string out;
    out.reserve(text.size());
    for (const char c : text) {
        if (c == '\'') {
            out += "'\\''";
        } else {
            out.push_back(c);
        }
    }
    return out;
}

std::string escape_zsh_desc(const std::string& text) {
    std::string out;
    out.reserve(text.size());
    for (const char c : text) {
        if (c == '[' || c == ']' || c == ':' || c == '\\') {
            out.push_back('\\');
            out.push_back(c);
        } else if (c == '\'') {
            out += "'\\''";
        } else {
            out.push_back(c);
        }
    }
    return out;
}

std::string format_man_placeholder(const OptionMeta& opt) {
    if (opt.value_placeholder.empty()) {
        return "VALUE";
    }
    std::string p = opt.value_placeholder;
    if (p.size() >= 2 && p.front() == '<' && p.back() == '>') {
        p = p.substr(1, p.size() - 2);
    }
    for (char& c : p) {
        c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    }
    return p;
}

void emit_man_command_options(std::ostringstream& out, const CommandSpec& cmd, const bool include_heading) {
    if (include_heading) {
        out << "# osmium " << cmd.name << "\n\n";
    }

    std::vector<std::string> groups;
    for (const auto& opt : cmd.options) {
        if (std::find(groups.begin(), groups.end(), opt.group) == groups.end()) {
            groups.push_back(opt.group);
        }
    }

    for (const auto& group : groups) {
        out << (include_heading ? "## " : "# ") << group << "\n\n";
        for (const auto& opt : cmd.options) {
            if (opt.group != group) {
                continue;
            }
            if (!opt.short_name.empty()) {
                out << '-' << opt.short_name << ", ";
            }
            out << "\\--" << opt.long_name;
            if (opt.takes_value) {
                out << '=' << format_man_placeholder(opt);
            }
            out << '\n';
            out << ":   " << opt.description;
            if (!opt.description.empty() && opt.description.back() != '.') {
                out << '.';
            }
            if (opt.default_value) {
                out << " Default: " << *opt.default_value << '.';
            }
            if (opt.is_repeatable) {
                out << " Can be specified multiple times.";
            }
            out << "\n\n";
        }
    }
}

